def circ_block_indices(names):
    out = {}
    for j, nm in enumerate(names):
        k = int(nm[1]); out.setdefault(k, []).append(j)
    return out


def diag_columns(R):
    """the 15 diagonal coordinates (odd blocks, (i, i) entries) as 75-vectors"""
    p = R.p; cols = []; names = []
    for k, pairs, off in BLOCKS:
        if k % 2 == 0: continue
        for i in range(5):
            v = [0] * NSP; v[off + pairs.index((i, i))] = 1; cols.append(v); names.append("d%d_%d" % (k, i))
    return cols, names


# ------------------------------------------------------------------ univariate roots over F_p (Cantor-Zassenhaus on the distinct-root part)
def pmod(a, b, p):
    a = list(g5.ptrim(a)); b = g5.ptrim(b)
    if b == [0]: raise ZeroDivisionError
    inv = pow(b[-1], p - 2, p)
    while len(a) >= len(b) and a != [0]:
        f = a[-1] * inv % p; sh = len(a) - len(b)
        for i, y in enumerate(b): a[sh + i] = (a[sh + i] - f * y) % p
        a = g5.ptrim(a)
    return a


def ppowmod(base, e, mod, p):
    result = [1]; b = pmod(base, mod, p)
    while e:
        if e & 1: result = pmod(g5.pmul(result, b, p), mod, p)
        b = pmod(g5.pmul(b, b, p), mod, p); e >>= 1
    return result


def roots_fp(f, p, rng):
    """all roots in F_p of the polynomial f (coefficient list, low to high), each once"""
    f = g5.ptrim([x % p for x in f])
    if len(f) <= 1: return []
    xp = ppowmod([0, 1], p, f, p)                              # x^p mod f
    g = g5.pgcd(f, g5.psub(xp, [0, 1], p), p)                  # product of the distinct linear factors
    inv = pow(g[-1], p - 2, p); g = [x * inv % p for x in g]
    out = []
    def split(h):
        if len(h) == 1: return
        if len(h) == 2: out.append((-h[0]) * pow(h[1], p - 2, p) % p); return
        while True:
            a = rng.randrange(p)
            t = ppowmod([a, 1], (p - 1) // 2, h, p); t = g5.psub(t, [1], p)
            d = g5.pgcd(h, t, p)
            if 1 < len(d) < len(h):
                dd = [x * pow(d[-1], p - 2, p) % p for x in d]
                q = pdiv(h, dd, p); split(dd); split(q); return
    split(g)
    return sorted(out)


def pdiv(a, b, p):
    """exact quotient a / b"""
    a = list(g5.ptrim(a)); b = g5.ptrim(b); q = [0] * max(1, len(a) - len(b) + 1); inv = pow(b[-1], p - 2, p)
    while len(a) >= len(b) and a != [0]:
        f = a[-1] * inv % p; sh = len(a) - len(b); q[sh] = f
        for i, y in enumerate(b): a[sh + i] = (a[sh + i] - f * y) % p
        a = g5.ptrim(a)
    return g5.ptrim(q)


def det_fp(M, p):
    M = [list(r) for r in M]; n = len(M); d = 1
    for c in range(n):
        piv = next((r for r in range(c, n) if M[r][c]), None)
        if piv is None: return 0
        if piv != c: M[c], M[piv] = M[piv], M[c]; d = (-d) % p
        d = d * M[c][c] % p; inv = pow(M[c][c], p - 2, p)
        for r in range(c + 1, n):
            if M[r][c]:
                f = M[r][c] * inv % p
                for k in range(c, n): M[r][k] = (M[r][k] - f * M[c][k]) % p
    return d
