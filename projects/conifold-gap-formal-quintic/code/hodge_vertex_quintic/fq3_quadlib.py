def kernel_basis(rows, ncols, p):
    """basis (list of vectors) of {t : rows . t = 0}"""
    return nullspace_fp(rows, ncols, p)


def compose_cols(C, K, p):
    """vectors C . k for k in K (C: list of columns of length n; k: coordinate vectors over the columns)"""
    n = len(C[0]); return [[sum(C[j][v] * k[j] for j in range(len(C))) % p for v in range(n)] for k in K]


def restricted_hom(Q, x0, B):
    """homogeneous part matrices of the restrictions Q_Gamma(x0 + B t): dict graph -> QuadForm in t; also returns max |c0|, |b|"""
    out = {}; bad = 0
    for i, q in Q.items():
        r = q.restrict(x0, B); out[i] = r
        if r.c0 or any(r.b): bad += 1
    return out, bad


def span_dim_forms(forms, p):
    """dimension of the span of the quadratic forms (flattened upper triangles)"""
    rows = []
    for q in forms:
        n = q.n; rows.append([q.A[i][j] for i in range(n) for j in range(i, n)])
    return rank_fp(rows, p)


# ------------------------------------------------------------------ Hilbert function of the ideal (q_1..q_5) in degree d
def monomials(n, d):
    """exponent tuples of degree d in n variables (lexicographic)"""
    out = []
    for c in itertools.combinations_with_replacement(range(n), d):
        e = [0] * n
        for v in c: e[v] += 1
        out.append(tuple(e))
    return out


def form_as_poly(q):
    """{exponent tuple: coeff} of the homogeneous quadratic form"""
    n = q.n; P = {}
    for i in range(n):
        for j in range(i, n):
            c = q.A[i][j] if i == j else (2 * q.A[i][j]) % q.p
            if c:
                e = [0] * n; e[i] += 1; e[j] += 1; P[tuple(e)] = c
    return P


def ideal_rank_degree(forms, d, p):
    """rank of the span of {q_k * m : m monomial of degree d-2} in degree d (sparse elimination); returns (rank, number of monomials)"""
    n = forms[0].n; polys = [form_as_poly(q) for q in forms]
    monos = monomials(n, d - 2); allm = monomials(n, d); index = {m: k for k, m in enumerate(allm)}
    rows = []
    for P in polys:
        for m in monos:
            row = {}
            for e, c in P.items():
                e2 = tuple(a + b for a, b in zip(e, m)); row[index[e2]] = c
            rows.append(row)
    # sparse Gaussian elimination over F_p (rows as dicts)
    pivots = {}; rank = 0
    for row in rows:
        row = dict(row)
        while row:
            c = min(row)
            if c in pivots:
                prow = pivots[c]; f = row[c] * pow(prow[c], p - 2, p) % p
                for k, v in prow.items():
                    nv = (row.get(k, 0) - f * v) % p
                    if nv: row[k] = nv
                    else: row.pop(k, None)
            else:
                pivots[c] = row; rank += 1; break
    return rank, len(allm)


def expected_ci(n, d, r):
    """coefficient of t^d in (1 - t^2)^r / (1 - t)^n (Hilbert function of a complete intersection of r quadrics in n variables)"""
    from math import comb
    tot = 0
    for k in range(r + 1):
        e = d - 2 * k
        if e < 0: continue
        tot += (-1) ** k * comb(r, k) * comb(e + n - 1, n - 1)
    return tot


# ------------------------------------------------------------------ common zeros on small spaces
def common_zeros_small(forms, p):
    """forms: list of QuadForm (homogeneous) in m <= 3 variables; returns ('none' | 'all' | list of projective points (tuples)), method"""
    m = forms[0].n
    if m == 1:
        return (['(1)'] if all(q.A[0][0] == 0 for q in forms) else []), "dim 1"
    if m == 2:
        # binary forms a t^2 + b t s + c s^2; point at infinity (t, s) = (1, 0): a = 0 for all; finite points s = 1: common roots in t
        pts = []
        if all(q.A[0][0] == 0 for q in forms): pts.append((1, 0))
        polys = [[q.A[1][1] % p, (2 * q.A[0][1]) % p, q.A[0][0] % p] for q in forms]        # in t with s = 1: a t^2 + b t + c -> [c, b, a]
        g = None
        for P in polys:
            P = g5.ptrim(P); g = P if g is None else g5.pgcd(g, P, p)
        if g == [0]: return 'all', "dim 2 (all forms vanish identically on the line)"
        if len(g) - 1 >= 1:
            # roots of g (degree <= 2)
            if len(g) == 2: pts.append(((-g[0]) * pow(g[1], p - 2, p) % p, 1))
            else:
                a, b, c = g[2], g[1], g[0]; D = (b * b - 4 * a * c) % p; r = sqrt_fp(D, p)
                if r is not None: pts += [((-b + s * r) * pow(2 * a, p - 2, p) % p, 1) for s in (1, -1)]
                else: pts.append(('irrational pair', str(D)))
        return pts, "dim 2 (gcd of binary forms, degree %d)" % (len(g) - 1)
    if m == 3:
        # dehomogenise z = 1: conics in (x, y) -> resultants in y (quadratics in y), gcd in x; plus the line z = 0 (binary forms in x, y)
        def to6(q):   # coefficients in the MONOS order of genus3_step5b: (0,0),(1,0),(0,1),(2,0),(1,1),(0,2) with z = 1
            A = q.A; return [A[2][2] % p, 2 * A[0][2] % p, 2 * A[1][2] % p, A[0][0] % p, 2 * A[0][1] % p, A[1][1] % p]
        c6 = [to6(q) for q in forms]
        g = None; degs = []
        for j in range(1, len(c6)):
            r = g5.resultant_t2(c6[0], c6[j], p); degs.append(len(r) - 1); g = r if g is None else g5.pgcd(g, r, p)
        info = "dim 3: resultant degrees %s, gcd degree %d" % (degs, len(g) - 1)
        if g == [0]: return 'degenerate', info + " (a resultant vanishes identically)"
        # the line at infinity z = 0: binary forms in (x, y)
        bin_forms = [QuadForm(p, 0, [0, 0], [[q.A[0][0], q.A[0][1]], [q.A[1][0], q.A[1][1]]]) for q in forms]
        inf_pts, _ = common_zeros_small(bin_forms, p)
        pts = [("z=0", pt) for pt in (inf_pts if isinstance(inf_pts, list) else [])]
        if len(g) - 1 >= 1 and len(g) - 1 <= 2:
            if len(g) == 2: roots = [(-g[0]) * pow(g[1], p - 2, p) % p]
            else:
                a, b, c = g[2], g[1], g[0]; D = (b * b - 4 * a * c) % p; r = sqrt_fp(D, p)
                roots = [((-b + s * r) * pow(2 * a, p - 2, p) % p for s in (1, -1))] if r is not None else []
                roots = list(roots[0]) if roots else []
            for x in roots:
                # common y: gcd of the univariate quadratics in y at this x
                gy = None
                for c in c6:
                    poly = [(c[0] + c[1] * x + c[3] * x * x) % p, (c[2] + c[4] * x) % p, c[5] % p]
                    poly = g5.ptrim(poly); gy = poly if gy is None else g5.pgcd(gy, poly, p)
                if gy != [0] and len(gy) == 2: pts.append((x, (-gy[0]) * pow(gy[1], p - 2, p) % p, 1))
                elif gy == [0] or len(gy) > 2: pts.append((x, "y-gcd degree %d" % (len(gy) - 1), 1))
        elif len(g) - 1 > 2:
            pts.append(("x-gcd of degree %d: roots not extracted" % (len(g) - 1),))
        return pts, info
    raise ValueError("dimension > 3")


