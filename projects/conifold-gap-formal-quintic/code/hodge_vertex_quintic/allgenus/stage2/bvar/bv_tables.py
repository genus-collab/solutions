# -*- coding: utf-8 -*-
"""bv_tables.py -- collect the bv_run tables (tab_*.json in --dir) into BV_TABLES.md (run summary + graph-by-graph status).
Status per outer graph: R = regular ([u^0..u^(2g-3)] = 0), S<k> = singular with first non-zero coefficient at u^k, . = not computed.
Run: py -I -B bv_tables.py <dir with tab_*.json> <output .md>
"""
import os, sys, json, glob

ORDER = ["R0", "S1", "S2", "S3", "S4", "S5"]


def load(d):
    out = []
    for f in sorted(glob.glob(os.path.join(d, "tab_*.json"))):
        j = json.load(open(f)); j['file'] = os.path.basename(f); out.append(j)
    return out


def status(j):
    g = j['g']; npol = 2 * g - 2; st = {}
    for (i, E, gv, c) in j['rows']:
        k = next((n for n in range(npol) if c[n] != '0'), None)
        st[i] = ("R" if k is None else "S%d" % k, E, tuple(gv))
    return st


def main():
    d = sys.argv[1]; outp = sys.argv[2]; runs = load(d); L = []
    L.append("# B-variation: tables generated by bv_tables.py from the bv_run tables (exact residues mod p, rational reconstruction)")
    L.append("")
    L.append("Status per outer graph: `R` regular (`[u^0..u^(2g-3)] = 0`), `S<k>` singular, first non-zero coefficient at `u^k`.")
    L.append("Vertex column: coefficients of `T''^(2-2g) .. T''^-1` of the vertex graph, `T'' = c0 Int_0^u f`. Window `u^0..u^(K-1)`.")
    L.append("")
    L.append("## 1. Runs")
    L.append("")
    L.append("| system | g | p | norm | control | maxout | K | edge graphs | regular | singular (graph: first order) | vertex in T'' | CPU s |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    key = lambda j: (j['g'], j['ctrl'] != 'none' or j['norm'] != 'canon', ORDER.index(j['system']), j['prime'], j['norm'], j['ctrl'], j['maxout'] or 0)
    for j in sorted(runs, key=key):
        st = status(j); sing = {i: s for i, (s, E, gv) in st.items() if s != "R"}
        K = len(next(iter(j['table'].values()))) if j['table'] else 0
        orders = sorted(set(s for s in sing.values()))
        if len(sing) == len(st) and len(orders) == 1: sing_txt = "all %d, at u^%s" % (len(st), orders[0][1:])
        else: sing_txt = ", ".join("%d: %s" % (i, s[1:]) for i, s in sorted(sing.items())) or "none"
        L.append("| %s | %d | 2^%s-1 | %s | %s | %s | %d | %d | %d | %s | %s | %.0f |" % (
            j['system'], j['g'], j['prime'], j['norm'], j['ctrl'], j['maxout'] if j['maxout'] is not None else "all", K, len(st),
            len(st) - len(sing), sing_txt,
            " ; ".join(j['vertex']), j.get('cpu', 0)))
    for g in (2, 3, 4):
        sel = [j for j in sorted(runs, key=key) if j['g'] == g]
        if not sel: continue
        L.append(""); L.append("## %d. Genus %d, graph by graph" % (g, g)); L.append("")
        cols = ["%s %s%s%s%s" % (j['system'], j['prime'], "" if j['norm'] == 'canon' else " stored", "" if j['ctrl'] == 'none' else " " + j['ctrl'],
                                "" if j['maxout'] is None else " out%d" % j['maxout']) for j in sel]
        sts = [status(j) for j in sel]
        idx = sorted(set(i for s in sts for i in s))
        if g == 4:
            idx = [i for i in idx if all(i in s for s in sts)]       # graphs with <= 2 edges (the full run: section 1)
            L.append("Graphs with at most two edges (exact at maxout 2). The full run (all 378 edge graphs) is summarised in s.1."); L.append("")
        L.append("| graph | E | g_v | " + " | ".join(cols) + " |")
        L.append("|---|---|---|" + "---|" * len(cols))
        for i in idx:
            E, gv = next((s[i][1], s[i][2]) for s in sts if i in s)
            L.append("| %d | %d | %s | " % (i, E, ",".join(map(str, gv))) + " | ".join((s[i][0] if i in s else ".") for s in sts) + " |")
    open(outp, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote %s (%d lines, %d runs)" % (outp, len(L), len(runs)))


if __name__ == "__main__":
    main()
